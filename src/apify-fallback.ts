import type { CaptionTrack, SubtitleResult } from './youtube-fetcher.js';

/**
 * Optional hosted fallback for when YouTube refuses the direct fetch.
 *
 * YouTube answers some networks with HTTP 429 or an empty transcript no matter
 * what the request looks like (cloud hosts, VPN exits, shared office IPs), and
 * its internal API changes from time to time. When `APIFY_TOKEN` is set, a
 * failed fetch is retried once through the YouTube Transcripts Actor on Apify
 * (`johnvc/YoutubeTranscripts`), billed to that token's Apify account (about
 * $0.003 per transcript; failed videos are not charged).
 *
 * With the variable unset nothing changes: the original error is thrown as
 * before. If the fallback fails too, the original error is thrown, unless the
 * fallback could see the video and says why it has no transcript.
 */

const ACTOR_URL =
  'https://api.apify.com/v2/acts/johnvc~YoutubeTranscripts/run-sync-get-dataset-items';
const TIMEOUT_SECS = 120;

/** Errors that mean the input was wrong, not that YouTube refused us. */
const INPUT_ERRORS = [/^Invalid video ID/, /^Language '.*' not available/];

interface ActorRow {
  error?: boolean;
  error_type?: string;
  is_blocking_error?: boolean;
  language?: string;
  language_code?: string;
  is_generated?: boolean;
  timestamped?: { text?: string; start?: number; duration?: number }[];
  available_transcripts?: { language?: string; language_code?: string; is_generated?: boolean }[];
  title?: string;
  channel_name?: string;
  view_count?: number;
}

/** The fallback reached YouTube and has a definite answer; don't hide it. */
class FallbackVerdict extends Error {}

/**
 * Returns the Apify token from `APIFY_TOKEN`, or undefined when unset.
 */
export function apifyToken(): string | undefined {
  return process.env.APIFY_TOKEN?.trim() || undefined;
}

/**
 * Called with the error from `getSubtitles`. Returns the transcript from the
 * hosted fallback, or throws: the original error when there is no token, the
 * input was invalid or the fallback failed; a clearer one when the fallback
 * shows the video has no usable transcript.
 */
export async function apifyFallback(
  error: unknown,
  options: { videoID: string; lang?: string }
): Promise<SubtitleResult> {
  const token = apifyToken();
  const message = error instanceof Error ? error.message : String(error);
  if (!token || INPUT_ERRORS.some(re => re.test(message))) {
    throw error;
  }

  const { videoID, lang = 'en' } = options;
  console.error(`[apify-fallback] Direct fetch failed (${message}); retrying through Apify`);
  try {
    // Same order as getSubtitles: the requested language, then English,
    // then whatever the video has.
    let row = await runActor(videoID, lang === 'en' ? ['en'] : [lang, 'en'], token);
    const available = captionTracks(row);
    if (row.error_type === 'NoTranscriptFound' && available.length > 0) {
      row = await runActor(videoID, [available[0].languageCode], token);
    }
    return toSubtitleResult(row, lang, available);
  } catch (fallbackError) {
    if (fallbackError instanceof FallbackVerdict) {
      throw fallbackError;
    }
    console.error(`[apify-fallback] ${(fallbackError as Error).message}`);
    throw error;
  }
}

async function runActor(videoID: string, languages: string[], token: string): Promise<ActorRow> {
  const response = await fetch(`${ACTOR_URL}?timeout=${TIMEOUT_SECS}&clean=true`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` },
    body: JSON.stringify({
      youtube_url: `https://www.youtube.com/watch?v=${videoID}`,
      languages,
    }),
    signal: AbortSignal.timeout((TIMEOUT_SECS + 10) * 1000),
  });
  if (!response.ok) {
    throw new Error(`Apify fallback failed: HTTP ${response.status}`);
  }
  const rows = await response.json();
  const row = Array.isArray(rows)
    ? rows.find(r => r && typeof r === 'object' && (r.timestamped || r.error))
    : undefined;
  if (!row) {
    throw new Error('Apify fallback returned no transcript');
  }
  return row as ActorRow;
}

/** The tracks a NoTranscriptFound row lists; a successful row lists none. */
function captionTracks(row: ActorRow): CaptionTrack[] {
  return (row.available_transcripts || [])
    .filter(t => t.language_code)
    .map(t => ({
      languageCode: t.language_code as string,
      name: t.language || (t.language_code as string),
      isAutoGenerated: Boolean(t.is_generated),
    }));
}

function toSubtitleResult(row: ActorRow, requestedLang: string, available: CaptionTrack[]): SubtitleResult {
  if (row.error) {
    switch (row.error_type) {
      case 'TranscriptsDisabled':
      case 'NoTranscriptFound':
        throw new FallbackVerdict('No transcript available for this video. The video may not have captions enabled.');
      case 'VideoUnavailable':
      case 'InvalidVideoId':
        throw new FallbackVerdict('This video is unavailable.');
      default:
        throw new Error(`Apify fallback failed: ${row.error_type || 'unknown error'}`);
    }
  }

  const lines = (row.timestamped || [])
    .map(seg => ({
      text: String(seg.text ?? '').replace(/\s+/g, ' ').trim(),
      start: Number(seg.start) || 0,
      dur: Number(seg.duration) || 0,
    }))
    .filter(line => line.text.length > 0);
  if (lines.length === 0) {
    throw new Error('Apify fallback returned an empty transcript');
  }

  const actualLang = row.language_code || requestedLang;
  const track: CaptionTrack = {
    languageCode: actualLang,
    name: row.language || actualLang,
    isAutoGenerated: Boolean(row.is_generated),
  };
  return {
    lines,
    requestedLang,
    actualLang,
    availableLanguages: available.length > 0 ? available : [track],
    // The Actor doesn't return chapters, so strip_ads falls back to its prompt hint.
    adChapters: [],
    metadata: {
      title: row.title || '',
      author: row.channel_name || '',
      subscriberCount: '',
      viewCount: formatViews(row.view_count),
      publishDate: '',
    },
  };
}

/** 22205 -> "22.2k", matching the direct fetcher's metadata. */
function formatViews(views: number | undefined): string {
  if (typeof views !== 'number' || Number.isNaN(views)) return '';
  if (views >= 1_000_000) return (views / 1_000_000).toFixed(1) + 'M';
  if (views >= 1_000) return (views / 1_000).toFixed(1) + 'k';
  return String(views);
}
