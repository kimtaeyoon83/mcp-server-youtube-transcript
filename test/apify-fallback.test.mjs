// Offline tests for the optional Apify fallback (no network, no token):
//   npm run build && node --test test/apify-fallback.test.mjs
import { test, beforeEach, afterEach } from 'node:test';
import assert from 'node:assert/strict';
import { apifyFallback } from '../dist/apify-fallback.js';

// Trimmed from real Actor output (jNQXAC9IVRw, captured 2026-11-02).
const ZOO = {
  video_id: 'jNQXAC9IVRw',
  language: 'English',
  language_code: 'en',
  is_generated: false,
  timestamped: [
    { text: 'All right, so here we are, in front of the\nelephants', start: 1.2, duration: 2.16 },
    { text: 'really really long trunks', start: 7.974, duration: 4.642 },
    { text: '  ', start: 12, duration: 1 },
  ],
  title: 'Me at the zoo',
  channel_name: 'jawed',
  view_count: 438602468,
  success: true,
};
const NO_LANG = {
  error: true,
  error_type: 'NoTranscriptFound',
  is_blocking_error: false,
  available_transcripts: [
    { language: 'German', language_code: 'de', is_generated: false },
    { language: 'English (auto-generated)', language_code: 'en', is_generated: true },
  ],
};
const DIRECT_ERROR = new Error('Failed to fetch transcript API: HTTP 400: Bad Request');

const realFetch = globalThis.fetch;
let calls;

function stubFetch(...responses) {
  calls = [];
  globalThis.fetch = async (url, init) => {
    calls.push({ url, init, body: JSON.parse(init.body) });
    const next = responses.shift();
    if (next instanceof Error) throw next;
    const { status = 200, rows } = next;
    return new Response(JSON.stringify(rows), { status });
  };
}

beforeEach(() => {
  process.env.APIFY_TOKEN = 'apify_api_test';
});

afterEach(() => {
  globalThis.fetch = realFetch;
  delete process.env.APIFY_TOKEN;
});

test('without a token the original error is thrown and nothing is fetched', async () => {
  delete process.env.APIFY_TOKEN;
  stubFetch();
  await assert.rejects(apifyFallback(DIRECT_ERROR, { videoID: 'jNQXAC9IVRw' }), DIRECT_ERROR);
  assert.equal(calls.length, 0);
});

test('invalid input is not retried', async () => {
  stubFetch();
  const error = new Error('Invalid video ID: must be a non-empty string');
  await assert.rejects(apifyFallback(error, { videoID: '' }), error);
  assert.equal(calls.length, 0);
});

test('a failed direct fetch returns the hosted transcript', async () => {
  stubFetch({ rows: [ZOO] });
  const result = await apifyFallback(DIRECT_ERROR, { videoID: 'jNQXAC9IVRw', lang: 'en' });

  assert.deepEqual(result.lines, [
    { text: 'All right, so here we are, in front of the elephants', start: 1.2, dur: 2.16 },
    { text: 'really really long trunks', start: 7.974, dur: 4.642 },
  ]);
  assert.equal(result.actualLang, 'en');
  assert.deepEqual(result.adChapters, []);
  assert.deepEqual(result.metadata, {
    title: 'Me at the zoo',
    author: 'jawed',
    subscriberCount: '',
    viewCount: '438.6M',
    publishDate: '',
  });

  const [call] = calls;
  assert.match(call.url, /acts\/johnvc~YoutubeTranscripts\/run-sync-get-dataset-items/);
  assert.equal(call.init.headers.Authorization, 'Bearer apify_api_test');
  assert.deepEqual(call.body, {
    youtube_url: 'https://www.youtube.com/watch?v=jNQXAC9IVRw',
    languages: ['en'],
  });
});

test('a missing language falls back to English, then the first track', async () => {
  stubFetch({ rows: [NO_LANG] }, { rows: [{ ...ZOO, language: 'German', language_code: 'de' }] });
  const result = await apifyFallback(DIRECT_ERROR, { videoID: 'jNQXAC9IVRw', lang: 'ko' });

  assert.deepEqual(calls.map(c => c.body.languages), [['ko', 'en'], ['de']]);
  assert.equal(result.requestedLang, 'ko');
  assert.equal(result.actualLang, 'de');
  assert.deepEqual(result.availableLanguages.map(t => t.languageCode), ['de', 'en']);
  assert.equal(result.availableLanguages[1].isAutoGenerated, true);
});

test('a successful row reports its own track', async () => {
  stubFetch({ rows: [ZOO] });
  const result = await apifyFallback(DIRECT_ERROR, { videoID: 'jNQXAC9IVRw', lang: 'ko' });
  assert.deepEqual(calls[0].body.languages, ['ko', 'en']);
  assert.deepEqual(result.availableLanguages, [
    { languageCode: 'en', name: 'English', isAutoGenerated: false },
  ]);
});

test('a video the fallback can see but has no captions says so', async () => {
  stubFetch({ rows: [{ error: true, error_type: 'TranscriptsDisabled' }] });
  await assert.rejects(
    apifyFallback(DIRECT_ERROR, { videoID: 'jNQXAC9IVRw' }),
    /No transcript available for this video/
  );
});

test('an unavailable video says so', async () => {
  stubFetch({ rows: [{ error: true, error_type: 'VideoUnavailable' }] });
  await assert.rejects(apifyFallback(DIRECT_ERROR, { videoID: 'aaaaaaaaaaa' }), /unavailable/);
});

for (const [name, response] of [
  ['an HTTP error', { status: 402, rows: { error: { type: 'not-enough-usage' } } }],
  ['a network error', new TypeError('fetch failed')],
  ['an empty dataset', { rows: [] }],
  ['a non-list response', { rows: { foo: 1 } }],
  ['a blocked run', { rows: [{ error: true, error_type: 'RequestBlocked', is_blocking_error: true }] }],
  ['an empty transcript', { rows: [{ ...ZOO, timestamped: [{ text: ' ' }] }] }],
]) {
  test(`${name} from the fallback rethrows the original error`, async () => {
    stubFetch(response);
    await assert.rejects(apifyFallback(DIRECT_ERROR, { videoID: 'jNQXAC9IVRw' }), DIRECT_ERROR);
  });
}
